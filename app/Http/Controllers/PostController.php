<?php

namespace App\Http\Controllers;

use App\Models\Category;
use App\Models\ParentCategory;
use App\Models\Post;
use App\Http\Requests\StorePostRequest;
use App\Http\Requests\UpdatePostRequest;
use App\Jobs\SendPostNotificationJob;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\File;
use Intervention\Image\Drivers\Gd\Driver;
use Intervention\Image\ImageManager;

class PostController extends Controller
{
    public function addPost()
    {
        // Eager load subcategories to avoid N+1 query problem and keep view clean
        $parent_categories = ParentCategory::with('subcategories')->orderBy('ordering', 'asc')->get();

        // Fetch categories that don't have a parent
        $uncategorized = Category::where('parent', 0)->orWhereNull('parent')->get();

        return view('Back.Pages.posts.add', compact('parent_categories', 'uncategorized'));
    }

    public function storePost(StorePostRequest $request)
    {
        // Handle image upload with Intervention Image
        $file = $request->file('image');
        $filename = 'POST_'.date('Ymd').uniqid().'.'.$file->getClientOriginalExtension();

        $path = public_path('images/posts/');
        $thumb_path = public_path('images/posts/thumbnails/');

        // Create directories if they don't exist
        if (! file_exists($path)) {
            mkdir($path, 0755, true);
        }
        if (! file_exists($thumb_path)) {
            mkdir($thumb_path, 0755, true);
        }

        // Initialize Intervention ImageManager
        $manager = new ImageManager(new Driver);

        try {
            // 1. Process Main Image (Resize if larger than 1200px width to save space)
            $image = $manager->read($file);
            $image->scaleDown(width: 1200);
            $image->save($path.$filename);

            // 2. Process Thumbnail Image (Crop to fit exactly 600x400 for uniform blog cards)
            $thumbnail = $manager->read($file);
            $thumbnail->cover(width: 600, height: 400);
            $thumbnail->save($thumb_path.'thumb_'.$filename);

            $upload = true;
        } catch (\Exception $e) {
            $upload = false;
        }

        if ($upload) {
            // Create a new Post record
            $post = new Post;
            $post->author_id = auth()->id() ?? 1; // Fallback to 1 if not logged in just in case
            $post->category_id = $request->category_id;
            $post->title = $request->title;
            // The slug is automatically generated by the Sluggable trait
            $post->content = $request->content;
            $post->featured_image = $filename;
            $post->tags = $request->tags;
            $post->meta_description = $request->meta_description;
            $post->meta_keywords = $request->meta_keywords;
            $post->visibility = $request->visibility == 'public' ? 1 : 0;

            $post->save();

            // Dispatch newsletter notification job to all subscribers in the background
            if ((int)$post->visibility === 1 && $request->has('notify_subscribers')) {
                SendPostNotificationJob::dispatch($post);
            }

            return redirect()->route('admin.posts.all-posts')->with('success', 'Post has been created successfully!');
        } else {
            return back()->with('error', 'Something went wrong while uploading the image.')->withInput();
        }
    }

    public function allPosts()
    {
        return view('Back.Pages.posts.all-posts');
    }

    public function editPost($id)
    {
        $post = Post::findOrFail($id);
        
        $isPrivileged = auth()->user()->type->value === 'superAdmin';
        if (! $isPrivileged && $post->author_id !== auth()->id()) {
            abort(403, 'Unauthorized action.');
        }

        $parent_categories = ParentCategory::with('subcategories')->orderBy('ordering', 'asc')->get();
        $uncategorized = Category::where('parent', 0)->orWhereNull('parent')->get();

        return view('Back.Pages.posts.edit', compact('post', 'parent_categories', 'uncategorized'));
    }

    public function updatePost(UpdatePostRequest $request, $id)
    {
        $post = Post::findOrFail($id);

        $isPrivileged = auth()->user()->type->value === 'superAdmin';
        if (! $isPrivileged && $post->author_id !== auth()->id()) {
            abort(403, 'Unauthorized action.');
        }

        if ($request->hasFile('image')) {
            $file = $request->file('image');
            $filename = 'POST_'.date('Ymd').uniqid().'.'.$file->getClientOriginalExtension();

            $path = public_path('images/posts/');
            $thumb_path = public_path('images/posts/thumbnails/');

            $manager = new ImageManager(new Driver);

            try {
                $image = $manager->read($file);
                $image->scaleDown(width: 1200);
                $image->save($path.$filename);

                $thumbnail = $manager->read($file);
                $thumbnail->cover(width: 600, height: 400);
                $thumbnail->save($thumb_path.'thumb_'.$filename);

                // Delete old images
                if ($post->featured_image && File::exists($path.$post->featured_image)) {
                    File::delete($path.$post->featured_image);
                }
                if ($post->featured_image && File::exists($thumb_path.'thumb_'.$post->featured_image)) {
                    File::delete($thumb_path.'thumb_'.$post->featured_image);
                }

                $post->featured_image = $filename;
            } catch (\Exception $e) {
                return back()->with('error', 'Something went wrong while uploading the new image.')->withInput();
            }
        }

        $post->category_id = $request->category_id;
        $post->title = $request->title;
        $post->content = $request->content;
        $post->tags = $request->tags;
        $post->meta_description = $request->meta_description;
        $post->meta_keywords = $request->meta_keywords;
        $post->visibility = $request->visibility == 'public' ? 1 : 0;

        $post->save();

        // Dispatch newsletter notification job to all subscribers in the background
        if ((int)$post->visibility === 1 && $request->has('notify_subscribers')) {
            SendPostNotificationJob::dispatch($post, isUpdate: true);
        }

        return redirect()->route('admin.posts.all-posts')->with('success', 'Post has been updated successfully!');
    }
}
